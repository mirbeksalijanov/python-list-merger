def merge_and_show():
    """
    Функция демонстрирует базовое объединение списков
    и выводит результат в удобном виде.
    """
    
    # Задаем начальные данные (например, оценки или ID)
    group_a = [101, 102, 103]
    group_b = [201, 202, 203]

    print("--- Исходные данные ---")
    print(f"Группа А: {group_a}")
    print(f"Группа Б: {group_b}")

    # Процесс слияния с помощью оператора +
    # Это самый простой и эффективный способ для новичка
    combined_list = group_a + group_b

    print("\n--- Процесс объединения ---")
    print("Выполняю: combined_list = group_a + group_b...")

    # Вывод финального результата
    print("\n--- Итоговый результат ---")
    print(f"Объединенный список: {combined_list}")
    print(f"Всего элементов: {len(combined_list)}")

if __name__ == "__main__":
    # Запуск программы
    merge_and_show()